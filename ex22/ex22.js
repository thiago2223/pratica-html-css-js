//Crie um Array vazio. Use o método push() para adicionar os números 10, 20 e 30. Depois, use o método pop() para remover o último número. Imprima como o array ficou no final.
var numeros = []
numeros.push(10, 20, 30) //O método push serve para "empurrar" um novo elemento para o fim
numeros.pop()
